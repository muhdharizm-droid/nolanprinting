/**
 * Dynamic Payment Method translation helper
 */
export function translatePaymentMethod(method: string | null | undefined, lang: Language): string {
  if (!method) return "";
  const lower = method.toLowerCase();
  if (lower.includes("cash") || lower.includes("tunai")) return lang === "ms" ? "Tunai" : "Cash";
  if (lower.includes("card") || lower.includes("edc") || lower.includes("kad")) return lang === "ms" ? "Kad / EDC" : "Card / EDC";
  if (lower.includes("qr") || lower.includes("duitnow")) return "DuitNow QR";
  return method;
}

/**
 * Dynamic Gender translation helper
 */
export function translateGender(gender: string | null | undefined, lang: Language): string {
  if (!gender) return "";
  const g = gender.toLowerCase();
  if (g.startsWith("m") || g === "lelaki") return lang === "ms" ? "Lelaki" : "Male";
  if (g.startsWith("f") || g === "perempuan" || g === "wanita") return lang === "ms" ? "Perempuan" : "Female";
  return gender;
}

